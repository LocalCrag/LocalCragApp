/** Maps a Prime icon class string to a registered lucide icon name. `pi-fw` is skipped. */
export function lucideNameFromPrimeIcon(icon?: string | null): string | null {
  if (!icon) {
    return null;
  }
  if (icon.startsWith('lucide')) {
    return icon;
  }
  const token = icon
    .split(/\s+/)
    .find((part) => part.startsWith('pi-') && part !== 'pi-fw');
  return token ? (PI_TO_LUCIDE[token] ?? null) : null;
}
