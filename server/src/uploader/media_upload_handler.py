import io
import os
import uuid

import magic
from botocore.exceptions import ClientError
from flask import current_app
from PIL import Image, ImageOps, UnidentifiedImageError
from werkzeug.datastructures import FileStorage

from models.file import File
from uploader.do_s3 import get_s3_client, upload_file
from uploader.errors import InvalidFiletypeUploaded, InvalidImageTransform
from uploader.image_gps import extract_gps_from_image
from uploader.image_transform import apply_rotation_and_crop, is_identity_transform
from uploader.upload_handler_utils import (
    check_filesize_limit,
    get_image_bytes,
    get_max_file_size,
    get_max_image_size,
    payload_size,
    post_upload,
    store_tmp_file,
)

allowed_image_mime_types = ["image/jpeg", "image/png", "image/gif", "image/bmp"]
allowed_video_mime_types = {
    "video/mp4": "mp4",
    "video/webm": "webm",
    "video/quicktime": "mov",
    "video/ogg": "ogg",
}

image_sizes = {
    "xl": 2000,
    "l": 1000,
    "m": 500,
    "s": 100,
    "xs": 20,
}


def handle_file_upload(file: FileStorage) -> File:
    """
    Processes an uploaded media file.
    :param args: Request arguments.
    :return: Created media model.
    """
    # Save file in tmp folder
    id = uuid.uuid4().hex
    temp_folder, temp_path, file = store_tmp_file(file, id)

    # Get mime type before choosing the size limit. Videos can be larger than images.
    mime_type = magic.Magic(mime=True).from_file(temp_path)

    # Call the handler for the appropriate file type
    file_object = None
    if mime_type in allowed_video_mime_types:
        if not _video_uploads_enabled():
            post_upload(file, temp_folder)
            raise InvalidFiletypeUploaded()
        check_filesize_limit(file, get_max_file_size(), temp_folder)
        file_object = handle_video_upload(
            temp_path, file, id, allowed_video_mime_types[mime_type], content_type=mime_type
        )
    elif mime_type in allowed_image_mime_types:
        check_filesize_limit(file, get_max_image_size(), temp_folder)
        file_object = handle_image_upload(temp_path, file, id)
    else:
        check_filesize_limit(file, get_max_image_size(), temp_folder)
        try:
            file_object = handle_arbitrary_file_upload(file, id)
        except InvalidFiletypeUploaded:
            post_upload(file, temp_folder)
            raise

    # Clean up
    post_upload(file, temp_folder)
    return file_object


def handle_image_upload(path: str, file, qquuid):
    """
    Processes an uploaded image.
    :param path: Current path of the image.
    :param file: Uploaded file object.
    :param qquuid: Identifier for the image, generated by the uploader.
    :return: Media object representing the image.
    """
    img = Image.open(path)

    # GPS is stripped when the image is re-encoded; read it first.
    lat, lng = extract_gps_from_image(img)

    ImageOps.exif_transpose(img, in_place=True)
    return persist_processed_image(img, file.filename, qquuid, lat, lng)


def persist_processed_image(img, original_filename: str, qquuid: str, lat, lng) -> File:
    """
    Stores an image and its thumbnails. `img.format` selects the file extension.
    Thumbnails are resized from the previous size, matching the original upload path.
    """
    s3_client = get_s3_client()
    extension = img.format.lower()
    filename = "{}.{}".format(qquuid, extension)
    original_bytes = get_image_bytes(img)
    file_size = payload_size(original_bytes)
    upload_file(s3_client, original_bytes, filename)

    file_object = File()
    file_object.filename = filename[:120]  # Max length of db field
    file_object.original_filename = (original_filename or filename)[:120]
    file_object.height = img.height
    file_object.width = img.width
    file_object.thumbnail_xs = False
    file_object.thumbnail_s = False
    file_object.thumbnail_m = False
    file_object.thumbnail_l = False
    file_object.thumbnail_xl = False
    file_object.exif_lat = lat
    file_object.exif_lng = lng

    # Create thumbnails
    for size_key, size in image_sizes.items():
        if img.width > size:
            new_size = (size, round(img.height * (size / img.width)))
            old_format = img.format
            img = img.resize(new_size)
            img.format = old_format
        else:
            continue
        setattr(file_object, "thumbnail_{}".format(size_key), True)
        filename = "{}_{}.{}".format(qquuid, size_key, extension)
        thumbnail_bytes = get_image_bytes(img)
        file_size += payload_size(thumbnail_bytes)
        upload_file(s3_client, thumbnail_bytes, filename)

    file_object.file_size = file_size
    return file_object


def transform_stored_image(source: File, rotation: int, crop: dict | None) -> File:
    """
    Builds a new file from a clockwise rotation and optional crop of `source`.
    Returns `source` when the request does not change the pixels.
    """
    if not source.filename or not source.width or not source.height:
        raise InvalidImageTransform()
    if is_identity_transform(source.width, source.height, rotation, crop):
        return source

    img = _load_stored_image(source.filename)
    ImageOps.exif_transpose(img, in_place=True)
    if img.width != source.width or img.height != source.height:
        raise InvalidImageTransform()

    img = apply_rotation_and_crop(img, rotation, crop)
    if img.format == "JPEG" and img.mode not in ("RGB", "L"):
        converted = img.convert("RGB")
        converted.format = "JPEG"
        img = converted
    return persist_processed_image(
        img,
        source.original_filename,
        uuid.uuid4().hex,
        source.exif_lat,
        source.exif_lng,
    )


def _load_stored_image(filename: str) -> Image.Image:
    try:
        client = get_s3_client()
        stored = client.get_object(Bucket=current_app.config["S3_BUCKET"], Key=filename)
        img = Image.open(io.BytesIO(stored["Body"].read()))
        img.load()
        return img
    except (ClientError, UnidentifiedImageError, OSError) as exc:
        raise InvalidImageTransform() from exc


def handle_video_upload(path: str, file, qquuid: str, extension: str, content_type: str) -> File:
    """Stores an uploaded video without image thumbnails."""
    s3_client = get_s3_client()
    filename = f"{qquuid}.{extension}"
    with open(path, "rb") as stored:
        upload_file(s3_client, stored, filename, content_type=content_type)
    file_entity = File()
    file_entity.filename = filename[:120]
    file_entity.original_filename = (file.filename or filename)[:120]
    file_entity.file_size = os.path.getsize(path)
    return file_entity


def _video_uploads_enabled() -> bool:
    from util.videos import video_uploads_enabled

    return video_uploads_enabled()


def _is_reserved_video_extension(extension: str) -> bool:
    from util.videos import VIDEO_EXTENSIONS

    return f".{extension.lower()}" in VIDEO_EXTENSIONS


def handle_arbitrary_file_upload(file, qquuid) -> File:
    """
    Processes an uploaded file of any type.
    :param file: Uploaded file object.
    :param qquuid: Identifier for the image, generated by the uploader.
    :return: Created file model.
    """
    filename_parts = file.filename.split(".")
    extension = filename_parts[-1] if len(filename_parts) > 1 else ""
    # A real video is stored by handle_video_upload after libmagic accepts it.
    # Keeping a video extension here would let a non-video payload be attached as a video.
    if _is_reserved_video_extension(extension):
        raise InvalidFiletypeUploaded()

    s3_client = get_s3_client()
    file_entity = File()
    file_entity.filename = "{}.{}".format(qquuid, extension)
    file_entity.original_filename = file.filename
    file.stream.seek(0, os.SEEK_END)
    file_entity.file_size = file.stream.tell()

    # Move file to uploads folder destination
    file.stream.seek(0)
    upload_file(s3_client, file.stream, "{}.{}".format(qquuid, extension))
    return file_entity
