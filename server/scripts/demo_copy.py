# These fields are shown as text, so paragraph tags would appear on screen.
_PLAIN_TEXT_KINDS = {
    "comment",
    "reply",
    "ascent",
    "gallery",
    "explorer",
    "admin_body",
    *(f"comment_{kind}" for kind in _COMMENTS),
}


def _as_plain_text(value: str) -> str:
    return value.replace("</p><p>", "\n\n").replace("<p>", "").replace("</p>", "").strip()


for _kind in _PLAIN_TEXT_KINDS:
    _pool = TEMPLATES[_kind]
    if isinstance(_pool, str):
        TEMPLATES[_kind] = _as_plain_text(_pool)
    else:
        TEMPLATES[_kind] = tuple(_as_plain_text(_text) for _text in _pool)


def render(kind: str, index: int, **values) -> str:
    pool = TEMPLATES[kind]
    if isinstance(pool, str):
        pool = (pool,)
    text = pool[index % len(pool)]
    for key, value in values.items():
        text = text.replace("{" + key + "}", str(value))
    return text
